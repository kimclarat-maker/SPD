const DAY = 24 * 60 * 60 * 1000;

export function quarterOf(date: Date) {
  const q = Math.floor(date.getMonth() / 3);
  const start = new Date(date.getFullYear(), q * 3, 1);
  const end = new Date(date.getFullYear(), q * 3 + 3, 0, 23, 59, 59);
  return { label: `Q${q + 1} ${date.getFullYear()}`, code: `${date.getFullYear()}-Q${q + 1}`, start, end };
}

